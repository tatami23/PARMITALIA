  function ensureModule(){
    if (typeof modules !== "undefined" && Array.isArray(modules)) {
      const existing = modules.find(item => item.id === PAGE);
      if (existing) {
        existing.label = L("menuLabel");
        existing.subtitle = L("subtitle");
        return;
      }
      const index = modules.findIndex(item => item.id === "dashboard");
      modules.splice(index >= 0 ? index + 1 : modules.length, 0, {
        id: PAGE,
        label: L("menuLabel"),
        subtitle: L("subtitle"),
        roles: ["admin", "assistant"]
      });
    }
  }
  function upsertField(module, key, def, afterKeys){
    if (typeof schemas === "undefined") return;
    schemas[module] = schemas[module] || {title: module, fields: []};
    const fields = Array.isArray(schemas[module].fields) ? schemas[module].fields : [];
    const found = fields.find(item => item.key === key);
    if (found) Object.assign(found, def, {key});
    else {
      const after = (afterKeys || []).map(k => fields.findIndex(item => item.key === k)).filter(i => i >= 0).pop();
      fields.splice(after >= 0 ? after + 1 : fields.length, 0, Object.assign({key}, def));
    }
    schemas[module].fields = fields;
  }
