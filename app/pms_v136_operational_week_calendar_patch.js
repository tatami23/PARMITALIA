  function routeLine(item){
    const bits = [
      item.loadingPlace || item.pickupPlace || item.origin || item.from,
      item.deliveryPlace || item.destination || item.to
    ].filter(Boolean);
    return bits.length ? bits.join(" -> ") : "";
  }
  function itemMeta(item, code){
    const qty = [item.quantity, item.unit].filter(Boolean).join(" ");
    const rows = [
      [L("client", code), item.client || item.customer || item.targetClient],
      [L("supplier", code), item.supplier],
      [L("product", code), item.product || item.productName],
      [L("quantity", code), qty],
      [L("status", code), item.status]
    ].filter(row => row[1]);
    const route = routeLine(item);
    if (route) rows.push([L("loadDate", code), route]);
    return rows;
  }
  function scheduledDate(item){
    return String(item.scheduledDate || item.operationalDate || "").slice(0, 10);
  }
